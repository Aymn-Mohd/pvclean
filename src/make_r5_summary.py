"""Writes docs/R5_SUMMARY.md from the stored results and applies the Phase R5 rule as written. Every number is computed here. Run: python src/make_r5_summary.py"""
from __future__ import annotations
import json
import os
import sys
from typing import Any
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_r4_summary import CONTRACTS, FOLD_YEAR, FOLDS, MARKET, ci, compact, hit, load, sgn
from pvclean.data import repo_root, results_dir
from pvclean.stats import DRY_HIGH, DRY_LOW, dry_prediction, dry_rule

SITES = ("murcia", "badajoz", "a_coruna", "whyalla", "mount_gambier", "roma_qld")
NAME = {"murcia": "Murcia", "badajoz": "Badajoz", "a_coruna": "A Coruña", "whyalla": "Whyalla", "mount_gambier": "Mount Gambier", "roma_qld": "Roma"}


def case_years() -> list[dict[str, Any]]:
    """The 24 R5 case-years, with dry spell and soiling loss."""
    rain = load("r5_rain.json")["sites"]; out = []
    for c in CONTRACTS:
        d = load(f"results_r5_{c}.json"); loss = d["r5_meta"]["soiling_loss_pct"]
        for s in SITES:
            for f in FOLDS:
                r = d["r5"][f"soil0.30|{s}|{c}|{f}"]; y = FOLD_YEAR[f]
                out.append(dict(compact(r), site=s, market=r["market"], contract=c, fold=f, year=y, dry=rain[s]["years"][str(y)]["longest_run_without_5mm"], loss=loss[f"{s}|{y}"]))
    return out


def rule(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """The rule on case-year rows."""
    return dry_rule([(r["dry"], r["planner_ft"]["mean"]) for r in rows])


def table(w: Any, rows: list[dict[str, Any]]) -> None:
    """Predicted against actual sign."""
    w("| site | market | contract | year | longest dry spell (days) | predicted | mean [95% CI] | actual sign | match | wins | ties |\n|---|---|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        p = dry_prediction(r["dry"]); q = r["planner_ft"]
        w(f"| {NAME[r['site']]} | {MARKET[r['market']]} | {r['contract']} | {r['year']} | {r['dry']} | {p or 'none'} | {ci(q)} | {sgn(q['mean'])} | {hit(p, q['mean'])} | {q['wins']}/{q['n']} | {r['ties']} |")


def line(v: dict[str, Any]) -> str:
    """One rule result in words."""
    share = f"{100 * v['share_correct']:.1f}%" if v["n_predicted"] else "no predicted case-years"
    return f"{v['n_correct']} of {v['n_predicted']} = {share} with the predicted sign; predicted above 0: {v['n_predicted_pos']}; predicted at or below 0: {v['n_predicted_nonpos']}; no prediction: {v['n_no_prediction']}."


def main() -> None:
    C = case_years(); M = [r for r in C if r["contract"] == "merchant"]; P = [r for r in C if r["contract"] == "ppa"]
    V, VP, VA = rule(M), rule(P), rule(C); K = load("results_r5_kappa.json")
    o: list[str] = []; w = o.append
    w("# E1 Phase R5: the merchant dry-spell rule on unseen sites\n")
    w(f"Labels: **MAIN** is the pre-registered test, merchant contract only; **DESCRIPTIVE** is pre-registered but decides nothing; **POST HOC** was listed in the pre-registration and decides nothing. Pre-registration: `docs/records/decisions.md`, \"Phase R5\". Generated by `src/make_r5_summary.py`. Money is USD/yr, mean over 50 seeds with the 95% t-interval. Rule thresholds: {DRY_HIGH} and {DRY_LOW} days.\n")
    w("## Summary\n")
    w(f"- **R5 verdict: {V['verdict']}.** {line(V)}")
    w(f"- **PPA (DESCRIPTIVE):** {line(VP)} The rule would say {VP['verdict']}; this is not a verdict.")
    w(f"- **All 24 (DESCRIPTIVE):** {line(VA)} The rule would say {VA['verdict']}; this is not a verdict.\n")
    w("## 1. Prediction test, merchant (MAIN)\n")
    table(w, M)
    w(f"\nRule: {line(V)} **Verdict: {V['verdict']}.**\n")
    nw = rule([r for r in M if r["site"] != "whyalla"])
    pr = [r for r in M if dry_prediction(r["dry"])]; spans = lambda r: r["planner_ft"]["lo"] <= 0 <= r["planner_ft"]["hi"]; good = lambda r: hit(dry_prediction(r["dry"]), r["planner_ft"]["mean"]) == "yes"
    gs = sum(good(r) and spans(r) for r in pr); bs = sum(not good(r) and spans(r) for r in pr)
    w(f"Without Whyalla (DESCRIPTIVE; note 3 of the pre-registration: its rain tracks Port Augusta): {line(nw)}\n")
    w(f"How firm the label is: {gs} correct and {bs} wrong case-years have an interval that spans 0. Moving all of them against the prediction gives {V['n_correct'] - gs} of {V['n_predicted']}; moving all of them for it gives {V['n_correct'] + bs} of {V['n_predicted']}.\n")
    w("## 2. PPA (DESCRIPTIVE)\n")
    table(w, P)
    w(f"\n{line(VP)}\n")
    w("## 3. Per case-year detail (DESCRIPTIVE)\n")
    w("Soiling loss: energy without cleaning against a dust-free run. Value of cleaning: policy minus no cleaning. Quantity and timing: the R1 split of planner minus FT revenue.\n")
    w("| site | contract | year | dry spell | soiling loss % | value of cleaning, planner | value of cleaning, FT | rows, planner | rows, FT | quantity | timing | kappa |\n|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in C:
        w(f"| {NAME[r['site']]} | {r['contract']} | {r['year']} | {r['dry']} | {r['loss']:.1f} | {r['voc_planner']:+.0f} | {r['voc_ft']:+.0f} | {r['rows_planner']:.0f} | {r['rows_ft']:.0f} | {r['quantity']:+.0f} | {r['timing']:+.0f} | {r['kappa']:g} |")
    w("\n## 4. Wider kappa grid (POST HOC)\n")
    kk = lambda r: f"{r['site']}|{r['contract']}|{r['fold']}"
    w("Decides nothing. The rule column shows what the rule would say on this check; it is not a verdict.\n")
    w("| set | case-years | mean > 0 | mean <= 0 | correct / predicted | rule, not a verdict | same sign as main |\n|---|---|---|---|---|---|---|")
    for n, rows in (("merchant", M), ("PPA", P), ("all", C)):
        m = [K["rows"][kk(r)]["planner_ft"]["mean"] for r in rows]; v = dry_rule([(r["dry"], x) for r, x in zip(rows, m)])
        same = sum((x > 0) == (r["planner_ft"]["mean"] > 0) for r, x in zip(rows, m))
        w(f"| {n} | {len(m)} | {sum(x > 0 for x in m)} | {sum(x <= 0 for x in m)} | {v['n_correct']} / {v['n_predicted']} | {v['verdict']} | {same} / {len(m)} |")
    w(f"\nThe planner's parameters moved in {K['_meta']['planner_params_moved']} of {len(K['rows'])} case-years, and kappa is at the grid top in {K['_meta']['kappa_at_grid_top']}.\n")
    w("| site | contract | year | predicted | main | wider kappa | kappa chosen |\n|---|---|---|---|---|---|---|")
    for r in C:
        k = K["rows"][kk(r)]
        w(f"| {NAME[r['site']]} | {r['contract']} | {r['year']} | {dry_prediction(r['dry']) or 'none'} | {ci(r['planner_ft'])} | {ci(k['planner_ft'])} | {k['params']['proposed']['kappa']:g} |")
    extra = os.path.join(results_dir(), "r5_sanity.json")
    if os.path.exists(extra):
        w("\n## 5. Sanity checks (POST HOC)\n")
        for x in json.load(open(extra))["lines"]:
            w(f"- {x}")
    path = os.path.join(repo_root(), "docs", "R5_SUMMARY.md")
    with open(path, "w") as f:
        f.write("\n".join(o) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
