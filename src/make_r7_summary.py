"""Writes docs/R7_SUMMARY.md from the stored results. Phase R7 is SENSITIVITY: no rule, no verdict. Every number is computed here. Run: python src/make_r7_summary.py"""
from __future__ import annotations
import json
import os
import sys
from typing import Any
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_r4_summary import ci, load
from make_r6_summary import NAME, records
from pvclean.data import repo_root, results_dir
from pvclean.stats import HEADROOM_CUT, cluster_median_ci, paired

YEAR = {"Y2": 2024, "Y3": 2025}
PL = {"threshold": "plain", "ft": "FT", "proposed": "planner"}


def stored_rows() -> dict[str, dict[str, Any]]:
    """The stored R3 to R5 F2 records in the compact form of the R7 jobs."""
    out = {}
    for k, r in records().items():
        t = r["test"]["F2"]
        out[k] = dict(none=t["none"]["net"], net={p: t[p]["net"] for p in PL}, params={p: r["tuned"]["F2"][p]["params"] for p in PL},
                      planner_ft=paired(t["proposed"]["net"], t["ft"]["net"]), ft_plain=paired(t["ft"]["net"], t["threshold"]["net"]),
                      value={p: float(np.mean(np.subtract(t[p]["net"], t["none"]["net"]))) for p in PL})
    return out


def keys() -> list[str]:
    return list(load("results_r6_oracle.json")["rows"])


def qualifying() -> list[str]:
    O = load("results_r6_oracle.json")["rows"]
    return [k for k in O if float(np.mean(O[k]["value"])) >= HEADROOM_CUT]


def counts(rows: dict[str, Any], key: str) -> dict[str, int]:
    v = [r[key] for r in rows.values()]
    return dict(n=len(v), pos=sum(x["mean"] > 0 for x in v), above=sum(x["lo"] > 0 for x in v), below=sum(x["hi"] < 0 for x in v))


def cnt(c: dict[str, int]) -> str:
    return f"{c['pos']} / {c['above']} / {c['below']}"


def shares(rows: dict[str, Any]) -> dict[str, Any]:
    """Median share of FT and planner value against the plain policy's value; case-years with plain value <= 0 are dropped and counted."""
    ok = [r for r in rows.values() if r["value"]["threshold"] > 0]
    return dict(ft=float(np.median([r["value"]["ft"] / r["value"]["threshold"] for r in ok])), planner=float(np.median([r["value"]["proposed"] / r["value"]["threshold"] for r in ok])),
                dropped=len(rows) - len(ok))


def pct(x: float) -> str:
    return f"{100 * x:.1f}%" if np.isfinite(x) else "undefined"


def same_nets(a: dict[str, Any], b: dict[str, Any], pols: tuple[str, ...]) -> int:
    """Case-years where the per-seed nets of pols differ between two row sets."""
    return sum(any(not np.array_equal(a[k]["net"][p], b[k]["net"][p]) for p in pols) for k in a)


def main() -> None:
    st = stored_rows(); K = keys(); Q = qualifying(); o: list[str] = []; w = o.append
    w("# E1 Phase R7: sensitivity analyses requested by reviewers\n")
    w("**SENSITIVITY.** No hypothesis, no decision rule, no verdict. Definitions: `docs/records/decisions.md`, \"Phase R7 (sensitivity, specified before the runs)\". Generated by `src/make_r7_summary.py`. "
      f"Money is USD/yr. Value = mean over the 50 test seeds of net minus no cleaning. Every policy is retuned on the training years in every variant. Counts are \"mean above 0 / interval wholly above 0 / interval wholly below 0\" over the {len(K)} case-years, with paired 95% t-intervals over the 50 seeds. Qualifying case-years: the {len(Q)} with R6 oracle value at or above {HEADROOM_CUT:,.0f} USD/yr.\n")
    w(f"Stored baseline (R3 to R5, F2, defaults): planner minus FT {cnt(counts(st, 'planner_ft'))}; FT minus plain {cnt(counts(st, 'ft_plain'))}.\n")

    # a) forecasts
    F = load("results_r7_forecast.json"); A = F["arms"]
    w("## 1. Price forecasts (r7_forecast)\n")
    w("F4 is an INFORMATION UPPER BOUND (realised prices), not a deployable forecast. FT minus plain is the value of price information; planner minus FT the value of planner design. The plain threshold reads no prices.\n")
    w(f"| forecast | FT minus plain, counts | planner minus FT, counts | FT minus plain over the {len(Q)} qualifying: median [cluster 95% CI] | IQR | range |\n|---|---|---|---|---|---|")
    clus = [k.split("|")[0] for k in Q]
    fq = {}
    for n, a in A.items():
        r = a["rows"]; d = [r[k]["ft_plain"]["mean"] for k in Q]; cm = cluster_median_ci(d, clus, 2000, 0); fq[n] = cm
        lab = f"{n} (information upper bound)" if n == "F4" else n
        w(f"| {lab} | {cnt(counts(r, 'ft_plain'))} | {cnt(counts(r, 'planner_ft'))} | {cm['median']:+.0f} [{cm['lo']:+.0f}, {cm['hi']:+.0f}] | {np.percentile(d, 25):+.0f} to {np.percentile(d, 75):+.0f} | {min(d):+.0f} to {max(d):+.0f} |")
    pl_moved = sum(same_nets(A[n]["rows"], A["F2"]["rows"], ("threshold",)) for n in A)
    f2_moved = same_nets(A["F2"]["rows"], st, ("threshold", "ft", "proposed"))
    w(f"\nChecks: the F2 arm differs from the stored R3 to R5 nets of plain, FT and planner in {f2_moved} of {len(K)} case-years; the plain threshold's nets differ from its F2 nets in {pl_moved} case-year-arms across the {len(A)} forecasts. Cluster bootstrap: the {len(set(clus))} sites with qualifying case-years, B = 2000, numpy default_rng(0), percentile.\n")
    worst = min(((n, k, A[n]["rows"][k]["value"]["ft"] - A["F2"]["rows"][k]["value"]["ft"]) for n in ("F4",) for k in K), key=lambda x: x[2])
    w(f"F4 FT value minus F2 FT value: below -500 USD/yr in {sum(A['F4']['rows'][k]['value']['ft'] - A['F2']['rows'][k]['value']['ft'] < -500 for k in K)} case-years; lowest {worst[2]:+.0f} ({NAME[worst[1].split('|')[0]]} {worst[1].split('|')[1]} {YEAR[worst[1].split('|')[2]]}). "
      f"F4 planner value minus F2 planner value: median {np.median([A['F4']['rows'][k]['value']['proposed'] - A['F2']['rows'][k]['value']['proposed'] for k in K]):+.0f}; F4 FT minus F2 FT: median {np.median([A['F4']['rows'][k]['value']['ft'] - A['F2']['rows'][k]['value']['ft'] for k in K]):+.0f}.\n")

    # b) abstain
    B = load("results_r7_abstain.json")["arms"]["abstain"]["rows"]
    w("## 2. Abstaining planner (r7_abstain)\n")
    inf = [k for k in K if B[k]["params"]["proposed"]["kappa"] == float("inf")]
    w(f"Planner grid kappa {{0, 0.5, 1, 2, 4, 8, 16, 32, inf}}. Planner minus FT counts: {cnt(counts(B, 'planner_ft'))}, against {cnt(counts(st, 'planner_ft'))} stored. "
      f"Case-years tuned to kappa = inf (no missions): {len(inf)}{' (' + ', '.join(f'{NAME[k.split(chr(124))[0]]} {k.split(chr(124))[1]} {YEAR[k.split(chr(124))[2]]}' for k in inf) + ')' if inf else ''}. "
      f"Planner parameters changed from stored in {sum(B[k]['params']['proposed'] != st[k]['params']['proposed'] for k in K)} case-years; FT and plain nets changed in {same_nets(B, st, ('threshold', 'ft'))}.\n")
    w("| Brisbane | year | kappa stored | kappa abstain | planner value stored | planner value abstain | planner minus FT stored | planner minus FT abstain |\n|---|---|---|---|---|---|---|---|")
    for k in K:
        if k.startswith("brisbane|"):
            s, c, f = k.split("|")
            w(f"| {c} | {YEAR[f]} | {st[k]['params']['proposed']['kappa']:g} | {B[k]['params']['proposed']['kappa']:g} | {st[k]['value']['proposed']:+.0f} | {B[k]['value']['proposed']:+.0f} | {ci(st[k]['planner_ft'])} | {ci(B[k]['planner_ft'])} |")

    # c-e) dust, rain, cost
    w("\n## 3. Dust, rain and cost (r7_dust, r7_rain, r7_cost)\n")
    w("Share = policy value / plain value, median over case-years with plain value above 0 (dropped: the rest).\n")
    w("| variant | planner minus FT, counts | FT minus plain, counts | FT / plain, median | planner / plain, median | dropped |\n|---|---|---|---|---|---|")
    sb = shares(st)
    w(f"| stored baseline (dust 0.30%/day, rain 0.9 / 0.2, cost x1) | {cnt(counts(st, 'planner_ft'))} | {cnt(counts(st, 'ft_plain'))} | {pct(sb['ft'])} | {pct(sb['planner'])} | {sb['dropped']} |")
    lab = {"soil0.10": "dust 0.10%/day", "soil0.15": "dust 0.15%/day", "soil0.50": "dust 0.50%/day", "rain_full_recov=0.7": "rain >= 5 mm cleans 0.7", "rain_full_recov=1.0": "rain >= 5 mm cleans 1.0",
           "rain_light_recov=0.1": "rain 1-5 mm cleans 0.1", "rain_light_recov=0.3": "rain 1-5 mm cleans 0.3", "x0.5": "costs x0.5", "x2": "costs x2"}
    for f in ("dust", "rain", "cost"):
        for n, a in load(f"results_r7_{f}.json")["arms"].items():
            r = a["rows"]; sh = shares(r)
            w(f"| {lab.get(n, n)} | {cnt(counts(r, 'planner_ft'))} | {cnt(counts(r, 'ft_plain'))} | {pct(sh['ft'])} | {pct(sh['planner'])} | {sh['dropped']} |")

    # f) oracle split
    S = load("results_r7_oracle_split.json"); m = S["_meta"]; R = S["rows"]; seeds = m["seeds"]
    w(f"\n## 4. Which information makes up the headroom (r7_oracle_split)\n")
    w(f"The {len(R)} qualifying case-years, seeds {seeds[0]} to {seeds[-1]} only (the first {len(seeds)}, to bound runtime). Every oracle is an open-loop full-year plan, scored in the simulator. "
      "C: the stored R6 oracle (perfect prices, rain, dust and per-row soiling). A: perfect prices, rain only through the policies' rain forecast flags (closest valid variant; it sees all flags of the year but never the realised rain). "
      "B: F2 prices, perfect rain. D: perfect prices and rain, per-row soiling replaced by the station estimate. The R6 oracle uses per-row true soiling. Share = mean policy value / mean oracle value over these seeds.\n")
    w("| oracle | value / C, median (range) | FT share, median (range) | planner share, median (range) | plain share, median (range) | case-years with a policy above the oracle | schedule violations |\n|---|---|---|---|---|---|---|")
    pv = {}; REC = records()
    for k in R:
        t = REC[k]["test"]["F2"]; none = np.array(t["none"]["net"])[seeds]
        pv[k] = {p: float(np.mean(np.array(t[p]["net"])[seeds] - none)) for p in PL}
    for kd in ["C"] + m["kinds"]:
        ov = {k: float(np.mean(R[k][kd]["value"])) for k in R}; rel = [ov[k] / float(np.mean(R[k]["C"]["value"])) for k in R]
        sh = {p: [pv[k][p] / ov[k] for k in R if ov[k] > 0] for p in PL}   # an oracle with value <= 0 has no share; counted below
        above = sum(max(pv[k].values()) > ov[k] for k in R); nz = sum(ov[k] <= 0 for k in R); viol = sum(sum(R[k][kd].get("violations", [0])) for k in R) if kd != "C" else 0
        rng = lambda v: f"{100 * np.median(v):.1f}% ({100 * min(v):.1f}% to {100 * max(v):.1f}%)"
        w(f"| {kd}{f' ({nz} with value <= 0, no share)' if nz else ''} | {rng(rel)} | {rng(sh['ft'])} | {rng(sh['proposed'])} | {rng(sh['threshold'])} | {above} | {viol} |")
    w("\n| site | contract | year | C | A | B | D | FT | planner | plain |\n|---|---|---|---|---|---|---|---|---|---|")
    for k in R:
        s, c, f = k.split("|")
        w(f"| {NAME[s]} | {c} | {YEAR[f]} | " + " | ".join(f"{np.mean(R[k][kd]['value']):.0f}" for kd in ["C"] + m["kinds"]) + " | " + " | ".join(f"{pv[k][p]:.0f}" for p in ("ft", "proposed", "threshold")) + " |")
    w("\nWhat this split can and cannot separate. C is an upper bound on every policy (a full-information optimum). A, B and D are not: each is a fixed full-year plan made with one kind of "
      "information removed, while the policies see that information as the year unfolds (they observe rain after it falls, prices up to the day, and the measured soiling). A share above 100% "
      "against A, B or D means the policy beat that fixed plan. C minus A, C minus B and C minus D are therefore the value of each kind of information to a fixed full-year plan, not the part of "
      "the policies' gap to C caused by that kind of information. Each kind is removed alone, so the three losses need not add up to anything and are not a decomposition. The oracle cannot "
      "separate the value of reacting to observations from the value of the information itself.\n")

    # figure and sanity
    ax = os.path.join(results_dir(), "r7_fig_axes.json")
    if os.path.exists(ax):
        a = json.load(open(ax))
        w(f"\n## 5. Figure\n\n`paper/fig_policies.pdf`: {a['note']}\n")
    sp = os.path.join(results_dir(), "r7_sanity.json")
    if os.path.exists(sp):
        w("## 6. Sanity checks\n")
        for x in json.load(open(sp))["lines"]:
            w(f"- {x}")
    path = os.path.join(repo_root(), "docs", "R7_SUMMARY.md")
    with open(path, "w") as fh:
        fh.write("\n".join(o) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
