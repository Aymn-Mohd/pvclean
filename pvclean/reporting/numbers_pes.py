"""PES GM 2027 energy metrics (ANALYSIS, post-processing of existing results; no new runs).
Reads results/results.json (RQ1, stable generated markets).
Writes paper/numbers_pes.tex (macros) and paper/table_rq1_pes.tex (Table I with two energy rows).

Definitions (all per year, mean of the 50 test years, 1.0 MWp plant):
  E_rec      energy delivered with the policy minus energy delivered without robot cleaning, MWh
  v_rec      gross value per recovered MWh = (net value + cleaning and mission cost) / E_rec, USD/MWh
  e_clean    energy recovered per row cleaning, kWh
  spread     (max - min) / mean of E_rec over the four tuned policies of one contract, %
Energy intervals are unpaired; differences in E_rec between policies are descriptive only.
"""
from __future__ import annotations


def build(R: str, OUT: str, RES_OUT: str) -> None:
    """R: results directory with a trailing slash. OUT: paper directory. RES_OUT: where macros_pes.json goes."""
    import json
    from .macros import rnd

    r = json.load(open(R + "results.json"))
    cfg = r["config"]
    plant_kwp = cfg["n_rows"] * cfg["row_kwp"]
    CON = [("fixed", "Fix"), ("merchant", "Mer"), ("ppa", "Ppa"), ("capped", "Cap")]
    POL = ["fixed", "threshold", "econ", "proposed"]
    M = {}

    def grp(s):
        i, _, f = s.partition("."); neg = i.startswith("-"); i = i.lstrip("-")
        if len(i) > 4:
            i = "{,}".join([i[max(0, k - 3):k] for k in range(len(i), 0, -3)][::-1])
        return ("$-$" if neg else "") + i + ("." + f if f else "")

    def erec(c, p): return r["rq1"][c][p]["energy_rec_mwh"][0]
    def gross(c, p):
        x = r["rq1"][c][p]; return x["inc_net"][0] + x["maint_cost"][0] + x["insp_cost"][0]
    def ncl(c, p): return r["rq1"][c][p]["n_clean"][0]
    def vrec(c, p): return gross(c, p) / erec(c, p)

    best = {c: r["rq1"][c]["_best_baseline"] for c, _ in CON}
    M["PlantKwp"] = rnd(plant_kwp)
    M["EnergyNoneMwh"] = grp(rnd(r["rq1"]["fixed"]["proposed"]["energy_none_mwh"][0]))
    M["EnergyNoneCapMwh"] = grp(rnd(r["rq1"]["capped"]["proposed"]["energy_none_mwh"][0]))
    allrec = []
    for c, t in CON:
        vals = [erec(c, p) for p in POL]; allrec += vals
        mean = sum(vals) / len(vals)
        M["ErecSpread" + t] = rnd((max(vals) - min(vals)) / mean * 100, 1)
        M["ErecProp" + t] = rnd(erec(c, "proposed"))
        M["ErecBest" + t] = rnd(erec(c, best[c]))
        M["VrecProp" + t] = rnd(vrec(c, "proposed"), 1)
        M["VrecBest" + t] = rnd(vrec(c, best[c]), 1)
        M["KwhCleanProp" + t] = rnd(1000 * erec(c, "proposed") / ncl(c, "proposed"))
        M["KwhCleanBest" + t] = rnd(1000 * erec(c, best[c]) / ncl(c, best[c]))
    M["ErecMin"] = rnd(min(allrec)); M["ErecMax"] = rnd(max(allrec))
    M["ErecSpreadMax"] = rnd(max(float(M["ErecSpread" + t]) for _, t in CON), 1)
    M["YieldGainProp"] = rnd(1000 * erec("fixed", "proposed") / plant_kwp)     # kWh/kWp
    M["YieldGainPropPct"] = rnd(erec("fixed", "proposed") / r["rq1"]["fixed"]["proposed"]["energy_none_mwh"][0] * 100)
    # export cap: planner without contract valuation
    M["ErecNovalCap"] = rnd(erec("capped", "proposed_noval"), 1)
    M["ErecPropCapOne"] = rnd(erec("capped", "proposed"), 1)
    M["ErecNovalCapExtra"] = rnd(erec("capped", "proposed_noval") - erec("capped", "proposed"), 1)
    M["NclNovalCapExtra"] = rnd(ncl("capped", "proposed_noval") - ncl("capped", "proposed"))
    M["ErecCapLossPct"] = rnd((1 - erec("capped", "proposed") / erec("fixed", "proposed")) * 100)
    # merchant: value of the timing
    M["VrecGainMerPct"] = rnd((vrec("merchant", "proposed") / vrec("merchant", best["merchant"]) - 1) * 100, 1)

    with open(OUT + "numbers_pes.tex", "w") as f:
        f.write("% Auto-generated by src/make_outputs_pes.py from results/results.json. Do not edit.\n")
        for k, v in sorted(M.items()):
            assert k.isalpha(), k
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    json.dump(M, open(RES_OUT + "macros_pes.json", "w"), indent=1)

    # Table I with two energy rows (rows above are copied unchanged from the generated table_rq1.tex)
    t = open(OUT + "table_rq1.tex").read()
    cells_e = " & ".join(f"{rnd(erec(c, 'proposed'))} ({rnd(erec(c, best[c]))})" for c, _ in CON)
    cells_v = " & ".join(f"{rnd(vrec(c, 'proposed'), 1)} ({rnd(vrec(c, best[c]), 1)})" for c, _ in CON)
    rows = ("\\midrule\n"
            f"Energy recovered, MWh, planner (best baseline) & {cells_e} \\\\\n"
            f"Revenue per recovered MWh, USD & {cells_v} \\\\\n")
    assert t.count("\\bottomrule") == 1
    t = t.replace("\\bottomrule", rows + "\\bottomrule")
    t = t.replace("\\caption{Incremental net maintenance value over no robot cleaning, mean of 50 test years, USD per year for the 1.0 MWp plant (robot cleanings per year in brackets). The gain row is the paired mean difference to the best tuned baseline with its 95\\% confidence half-width.}",
                  "\\caption{Incremental net value of cleaning over no robot cleaning, mean of 50 test years, USD per year for the 1.0 MWp plant (row cleanings per year in brackets). The gain row is the paired mean difference to the best tuned baseline with its 95\\% half-width. The energy rows give the delivered energy recovered by cleaning and the contract revenue it earns per MWh (descriptive).}")
    assert "energy rows" in t
    open(OUT + "table_rq1_pes.tex", "w").write(t)
